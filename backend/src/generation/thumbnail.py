"""Thumbnail Generator.

Generates thumbnail prompts, variations, and clickability scores.
Does NOT generate text inside thumbnails.

Supports:
- Thumbnail prompt generation
- Variations
- Clickability score
- Visual composition
"""

from __future__ import annotations

from typing import Any

from src.core.logging import get_logger
from src.generation.schema import AssetCategory, GeneratedAsset, GenerationRequest


class ThumbnailGenerator:
    """Generates thumbnail prompts and metadata.

    Produces detailed image generation prompts optimized for
    YouTube thumbnails.  Does NOT generate text inside thumbnails.
    """

    def __init__(self) -> None:
        self._logger = get_logger(__name__)

    def generate_prompt(
        self,
        title: str,
        *,
        style: str = "vibrant",
        composition: str = "rule_of_thirds",
        emotion: str = "curiosity",
    ) -> str:
        """Generate a thumbnail prompt.

        Args:
            title: Video title for context.
            style: Visual style (vibrant, dramatic, minimal, bold).
            composition: Composition technique.
            emotion: Target emotion to evoke.

        Returns:
            A detailed prompt for image generation.
        """
        return (
            f"YouTube thumbnail image, no text, no words, no letters. "
            f"Style: {style}. Composition: {composition}. "
            f"Emotion: {emotion}. "
            f"High contrast, eye-catching, bold colors. "
            f"Subject: {title}. "
            f"Resolution: 1280x720. "
            f"Aspect ratio: 16:9."
        )

    def generate_variations(
        self,
        title: str,
        *,
        count: int = 3,
    ) -> list[str]:
        """Generate multiple thumbnail prompt variations.

        Args:
            title: Video title.
            count: Number of variations.

        Returns:
            List of thumbnail prompts.
        """
        styles = ["vibrant", "dramatic", "minimal", "bold", "cinematic"]
        compositions = ["rule_of_thirds", "centered", "diagonal", "symmetrical"]
        emotions = ["curiosity", "excitement", "surprise", "wonder"]

        variations: list[str] = []
        for i in range(count):
            style = styles[i % len(styles)]
            comp = compositions[i % len(compositions)]
            emotion = emotions[i % len(emotions)]
            variations.append(self.generate_prompt(title, style=style, composition=comp, emotion=emotion))
        return variations

    def compute_clickability_score(
        self,
        title: str,
        *,
        has_face: bool = False,
        has_contrast: bool = True,
        has_bold_colors: bool = True,
        emotion_appeal: float = 0.7,
    ) -> float:
        """Compute a clickability score for a thumbnail.

        Args:
            title: Video title.
            has_face: Whether the thumbnail contains a face.
            has_contrast: Whether the thumbnail has high contrast.
            has_bold_colors: Whether the thumbnail uses bold colors.
            emotion_appeal: Emotional appeal score (0.0 to 1.0).

        Returns:
            Clickability score (0.0 to 1.0).
        """
        score = 0.0
        if has_face:
            score += 0.3
        if has_contrast:
            score += 0.2
        if has_bold_colors:
            score += 0.2
        score += emotion_appeal * 0.3
        return min(1.0, score)

    def create_request(
        self,
        title: str,
        scene_id: str = "",
        project_id: str = "",
        *,
        style: str = "vibrant",
    ) -> GenerationRequest:
        """Create a generation request for a thumbnail.

        Args:
            title: Video title.
            scene_id: Scene identifier.
            project_id: Project identifier.
            style: Visual style.

        Returns:
            A ``GenerationRequest`` for thumbnail generation.
        """
        prompt = self.generate_prompt(title, style=style)
        return GenerationRequest(
            scene_id=scene_id,
            project_id=project_id,
            category=AssetCategory.THUMBNAIL,
            prompt=prompt,
            aspect_ratio="16:9",
            resolution="1280x720",
            metadata={"title": title, "style": style, "no_text": True},
        )

    def create_asset(
        self,
        title: str,
        scene_id: str = "",
        *,
        style: str = "vibrant",
        job_id: Any | None = None,
    ) -> GeneratedAsset:
        """Create a generated asset for a thumbnail prompt.

        Note: This creates the prompt asset, not the actual image.
        The image is generated by the executor via the image gateway.

        Args:
            title: Video title.
            scene_id: Scene identifier.
            style: Visual style.
            job_id: Optional job ID.

        Returns:
            A ``GeneratedAsset`` containing the thumbnail prompt.
        """
        prompt = self.generate_prompt(title, style=style)
        clickability = self.compute_clickability_score(title)
        return GeneratedAsset(
            scene_id=scene_id,
            category=AssetCategory.THUMBNAIL,
            provider="internal",
            model="thumbnail_generator",
            file_size_bytes=len(prompt.encode()),
            cost_usd=0.0,
            quality_score=clickability,
            generation_time_seconds=0.01,
            metadata={"prompt": prompt, "clickability_score": clickability, "title": title, "no_text": True},
        )
